import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

// Development-only regeneration: the share card's caption is committed as a vector path,
// so the server needs no fonts (hosts may have none to rely on) and no font parser.
const text = 'Scan to open';
const size = 30;
const font = opentype.parse(
  readFileSync('node_modules/@fontsource/ibm-plex-sans/files/ibm-plex-sans-latin-500-normal.woff')
    .buffer,
);
const path = font.getPath(text, 0, 0, size);
const box = path.getBoundingBox();
writeFileSync(
  'server/card-text.ts',
  `// Generated by scripts/generate-card-text.mjs: "${text}" in IBM Plex Sans Medium, ${size}px,
// with the baseline at y=0.
export const caption = {
  width: ${Math.ceil(font.getAdvanceWidth(text, size))},
  top: ${Math.floor(box.y1)},
  path: '${path.toPathData(1)}',
};
`,
);
